import { StrictMode } from 'react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { toast } from 'sonner'
import { act, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { MemoryRouter, useLocation } from 'react-router'
import MockAdapter from 'axios-mock-adapter'
import App from '@/App'
import api from '@/lib/api'
import { AuthProvider } from '@/context/AuthContext'
import { useAuth } from '@/context/useAuth'
import { baseMenus, menuNode } from './menu-fixtures'

const uuid = (n) => `11111111-1111-4111-8111-${String(n).padStart(12, '0')}`
const actor = { id: uuid(90), username: 'admin_fixture', email: 'admin@example.invalid', role: 'ADMIN' }
const roles = ['ADMIN', 'MANAGER', 'USER'].map((code, i) => ({ id: uuid(i + 50), code, name: code, createdAt: '2026-11-20T00:00:00.000Z', updatedAt: '2026-11-20T00:00:00.000Z' }))
const adminTree = { success: true, menus: [...baseMenus.menus, { id: uuid(3), menuName: 'System Management', menuPath: null, menuIcon: 'Settings', parentId: null, sortOrder: 30, canAccess: false,
  children: ['menus', 'roles', 'users'].map((name, i) => menuNode(`/admin/${name}`, ['Menu Management', 'Role Management', 'User Role Assignment'][i], { id: uuid(i + 4), parentId: uuid(3), sortOrder: i + 1 })) }],
  allowedPaths: [...baseMenus.allowedPaths, '/admin/menus', '/admin/roles', '/admin/users'] }
const menuRows = [...baseMenus.menus, adminTree.menus[2], ...adminTree.menus[2].children].map((m) => ({ id: m.id, menuName: m.menuName, menuPath: m.menuPath, menuIcon: m.menuIcon, parentId: m.parentId, sortOrder: m.sortOrder, isActive: true, createdAt: '2026-11-20T00:00:00.000Z', updatedAt: '2026-11-20T00:00:00.000Z' }))
const target = { id: uuid(91), username: 'target_fixture', email: 'target@example.invalid', role: 'USER', roleId: roles[2].id, isActive: true }
let mock
function Probe() { return <><output data-testid="path">{useLocation().pathname}</output><output data-testid="account">{useAuth().user?.username}</output></> }
const mount = (path = '/dashboard') => render(<StrictMode><MemoryRouter initialEntries={[path]}><AuthProvider><App /><Probe /></AuthProvider></MemoryRouter></StrictMode>)
const show = (path, title) => { mount(path); return screen.findByRole('heading', { name: title, exact: true }) }
beforeEach(() => {
  mock = new MockAdapter(api)
  mock.onGet('/auth/me').reply(200, { success: true, user: actor })
  mock.onGet('/me/menus').reply(200, adminTree)
  mock.onGet('/menus').reply(200, { success: true, menus: menuRows })
  mock.onGet('/roles').reply(200, { success: true, roles })
  mock.onGet(`/roles/${roles[2].id}/menus`).reply(200, { success: true, role: roles[2], menuIds: [uuid(2)] })
  mock.onGet('/users?page=1&pageSize=10').reply(200, { success: true, users: [target], total: 1, page: 1, pageSize: 10 })
  mock.onPost('/auth/logout').reply(200, { success: true })
})
afterEach(() => mock.restore())

describe('Menu loading, landing and route protection', () => {
  it('deduplicates menus in StrictMode and renders API groups/icons/active links', async () => {
    await show('/dashboard', `Welcome back, ${actor.username}!`)
    expect(mock.history.get.filter((r) => r.url === '/me/menus')).toHaveLength(1)
    expect(screen.getByText('System Management')).toBeInTheDocument()
    expect(screen.queryByRole('link', { name: 'System Management' })).not.toBeInTheDocument()
    expect(screen.getByRole('link', { name: 'Dashboard', exact: true })).toHaveAttribute('aria-current', 'page')
  })
  it.each(['/', '/login'])('uses Profile landing when Dashboard is denied from %s', async (path) => {
    mock.onGet('/me/menus').reply(200, { success: true, menus: [baseMenus.menus[1]], allowedPaths: ['/profile'] })
    await show(path, 'Your profile')
    expect(screen.getByTestId('path')).toHaveTextContent('/profile')
    expect(screen.queryByRole('link', { name: 'Dashboard', exact: true })).not.toBeInTheDocument()
    expect(screen.queryByRole('link', { name: 'Back to Dashboard' })).not.toBeInTheDocument()
  })
  it.each(['/dashboard', '/profile', '/admin/menus'])('direct denied URL %s shows 403', async (path) => {
    mock.onGet('/me/menus').reply(200, { success: true, menus: [], allowedPaths: [] })
    await show(path, 'You don’t have access to this page.')
    expect(screen.getByTestId('path')).toHaveTextContent('/403')
    expect(mock.history.get.filter((r) => r.url === '/menus')).toHaveLength(0)
  })
  it('empty permissions allow logout without redirect loops', async () => {
    mock.onGet('/me/menus').reply(200, { success: true, menus: [], allowedPaths: [] })
    await show('/', 'You don’t have access to this page.')
    await userEvent.setup().click(screen.getByRole('button', { name: 'Sign out', exact: true }))
    await screen.findByRole('heading', { name: 'Welcome back.' })
  })
  it('unknown URL remains 404 even when the API grants it', async () => {
    mock.onGet('/me/menus').reply(200, { success: true, menus: [menuNode('/unknown', 'Unknown')], allowedPaths: ['/unknown'] })
    await show('/unknown', 'This page isn’t here.')
    expect(screen.getByTestId('path')).toHaveTextContent('/unknown')
  })
  it('does not grant admin pages to a USER even if the menu payload includes them', async () => {
    mock.onGet('/auth/me').reply(200, { success: true, user: { ...actor, role: 'USER' } })
    await show('/admin/roles', 'You don’t have access to this page.')
    expect(mock.history.get.filter((r) => r.url === '/roles')).toHaveLength(0)
  })
  it('network error is not an empty grant response and retry restores the requested page', async () => {
    mock.resetHandlers()
    mock.onGet('/auth/me').reply(200, { success: true, user: actor })
    mock.onGet('/me/menus').networkErrorOnce()
    mock.onGet('/me/menus').reply(200, adminTree)
    await show('/profile', 'Navigation is unavailable.')
    expect(screen.getByTestId('path')).toHaveTextContent('/profile')
    await userEvent.setup().click(screen.getByRole('button', { name: 'Retry navigation' }))
    await screen.findByRole('heading', { name: 'Your profile' })
  })
  it('malformed permission data fails closed without rendering protected content', async () => {
    mock.onGet('/me/menus').reply(200, { success: true, menus: [], allowedPaths: ['/dashboard'] })
    await show('/dashboard', 'Navigation is unavailable.')
    expect(screen.queryByText(actor.email)).not.toBeInTheDocument()
  })
  it('waits for menu loading before displaying the protected page', async () => {
    let finish
    mock.onGet('/me/menus').reply(() => new Promise((resolve) => { finish = resolve }))
    await show('/profile', 'Loading your navigation…')
    expect(screen.queryByRole('heading', { name: 'Your profile' })).not.toBeInTheDocument()
    await act(async () => finish([200, adminTree]))
    await screen.findByRole('heading', { name: 'Your profile' })
  })
  it('a successful permissions reload revokes the current page', async () => {
    await show('/dashboard', `Welcome back, ${actor.username}!`)
    mock.onGet('/me/menus').reply(200, { success: true, menus: [baseMenus.menus[1]], allowedPaths: ['/profile'] })
    expect(screen.queryByRole('button', { name: 'Reload navigation' })).not.toBeInTheDocument()
    await userEvent.setup().click(screen.getByRole('button', { name: 'Check session' }))
    await screen.findByRole('heading', { name: 'You don’t have access to this page.' })
    expect(screen.getByRole('link', { name: 'Back to workspace' })).toHaveAttribute('href', '/profile')
  })
  it('background reload preserves an in-progress profile form when access is unchanged', async () => {
    await show('/profile', 'Your profile')
    await userEvent.setup().click(screen.getByRole('button', { name: 'Edit Profile' }))
    fireEvent.change(screen.getByLabelText(/^First Name/), { target: { value: 'Unsaved draft' } })
    fireEvent(window, new Event('focus'))
    await waitFor(() => expect(mock.history.get.filter((r) => r.url === '/me/menus')).toHaveLength(2))
    expect(screen.getByLabelText(/^First Name/)).toHaveValue('Unsaved draft')
  })
  it('stale menus cannot restore the old account after logout and same-account login', async () => {
    mock.resetHandlers()
    mock.onGet('/auth/me').reply(200, { success: true, user: actor })
    mock.onPost('/auth/logout').reply(200, { success: true })
    let finish
    mock.onGet('/me/menus').replyOnce(() => new Promise((resolve) => { finish = resolve }))
    mock.onGet('/me/menus').reply(200, baseMenus)
    await show('/dashboard', 'Loading your navigation…')
    await userEvent.setup().click(screen.getByRole('button', { name: 'Sign out' }))
    await screen.findByRole('heading', { name: 'Welcome back.' })
    mock.onPost('/auth/login').reply(200, { success: true, user: actor })
    fireEvent.change(screen.getByLabelText('Username'), { target: { value: actor.username } })
    fireEvent.change(screen.getByLabelText('Password'), { target: { value: 'synthetic-test-input' } })
    await userEvent.setup().click(screen.getByRole('button', { name: 'Sign in to your workspace' }))
    await screen.findByRole('heading', { name: `Welcome back, ${actor.username}!` })
    await act(async () => finish([200, { success: true, menus: [], allowedPaths: [] }]))
    expect(screen.getByRole('heading', { name: `Welcome back, ${actor.username}!` })).toBeInTheDocument()
  })
})

describe('Management screens', () => {
  it('menu edit is a modal, Escape discards changes and restores focus without a write', async () => {
    await show('/admin/menus', 'Menu Management')
    const edit = await screen.findByRole('button', { name: 'Edit Profile' })
    await userEvent.setup().click(edit)
    const dialog = screen.getByRole('dialog', { name: 'Edit menu' })
    expect(within(dialog).getByLabelText('Menu name')).toHaveFocus()
    fireEvent.change(within(dialog).getByLabelText('Menu name'), { target: { value: 'Unsaved name' } })
    await userEvent.setup().keyboard('{Escape}')
    await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
    expect(edit).toHaveFocus()
    expect(mock.history.put).toHaveLength(0)
  })
  it('a pending menu save cannot be dismissed or submitted twice', async () => {
    await show('/admin/menus', 'Menu Management')
    await userEvent.setup().click(await screen.findByRole('button', { name: 'Edit Profile' }))
    let finish
    mock.onPut(`/menus/${uuid(2)}`).reply(() => new Promise((resolve) => { finish = resolve }))
    await userEvent.setup().dblClick(screen.getByRole('button', { name: 'Save menu' }))
    await userEvent.setup().keyboard('{Escape}')
    expect(screen.getByRole('dialog', { name: 'Edit menu' })).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Cancel' })).toBeDisabled()
    expect(screen.queryByRole('button', { name: 'Close', exact: true })).not.toBeInTheDocument()
    expect(mock.history.put).toHaveLength(1)
    await act(async () => finish([200, { success: true, menu: menuRows[1] }]))
    await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
    expect(screen.getByText('Menu saved.')).toBeInTheDocument()
  })
  it('deferred Profile validation and duplicate-email notifications remain inline only', async () => {
    const errorToast = vi.spyOn(toast, 'error')
    await show('/profile', 'Your profile')
    await userEvent.setup().click(screen.getByRole('button', { name: 'Edit Profile' }))
    fireEvent.change(screen.getByLabelText('Email', { exact: true }), { target: { value: 'invalid' } })
    await userEvent.setup().click(screen.getByRole('button', { name: 'Save Changes' }))
    expect(screen.getByRole('alert')).toHaveTextContent('Enter a valid email')
    expect(errorToast).not.toHaveBeenCalled()
    fireEvent.change(screen.getByLabelText('Email', { exact: true }), { target: { value: 'taken@example.invalid' } })
    mock.onPatch('/profile/me').reply(409, { success: false })
    await userEvent.setup().click(screen.getByRole('button', { name: 'Save Changes' }))
    await screen.findByText('This email address is already in use. Try another one.')
    expect(screen.getByRole('dialog', { name: 'Edit Profile' })).toBeInTheDocument()
    expect(errorToast).not.toHaveBeenCalled()
  })
  it('deferred Menu and Role validation does not add error toasts', async () => {
    const errorToast = vi.spyOn(toast, 'error')
    const view = mount('/admin/menus')
    await userEvent.setup().click(await screen.findByRole('button', { name: 'Add menu', exact: true }))
    fireEvent.change(screen.getByLabelText('Menu name'), { target: { value: 'Valid name' } })
    fireEvent.change(screen.getByLabelText('Menu path (blank for group)'), { target: { value: '/bad?query' } })
    await userEvent.setup().click(screen.getByRole('button', { name: 'Save menu' }))
    expect(screen.getByRole('alert')).toHaveTextContent('Use an internal path')
    expect(errorToast).not.toHaveBeenCalled(); view.unmount()
    mount('/admin/roles')
    await userEvent.setup().click(await screen.findByRole('button', { name: 'Add role', exact: true }))
    fireEvent.change(screen.getByLabelText('Role code'), { target: { value: 'bad-code' } })
    fireEvent.change(screen.getByLabelText('Role name'), { target: { value: 'Role' } })
    await userEvent.setup().click(screen.getByRole('button', { name: 'Save role' }))
    expect(screen.getByLabelText('Role code').validity.patternMismatch).toBe(true)
    expect(errorToast).not.toHaveBeenCalled()
    expect(mock.history.post).toHaveLength(0)
  })
  it('deferred Avatar file and preview validation stays inline inside the photo dialog', async () => {
    const errorToast = vi.spyOn(toast, 'error')
    await show('/profile', 'Your profile')
    await userEvent.setup({ applyAccept: false }).upload(screen.getByLabelText('Choose profile photo'), new File(['invalid'], 'fixture.svg', { type: 'image/svg+xml' }))
    expect(screen.getByRole('dialog', { name: 'Change Photo' })).toBeInTheDocument()
    expect(screen.getByRole('alert')).toHaveTextContent('Choose a JPG, PNG or WebP image.')
    expect(errorToast).not.toHaveBeenCalled()
    await userEvent.setup().click(screen.getByRole('button', { name: 'Cancel', exact: true }))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  })
  it('self-role changes require an Alert Dialog and Cancel never sends a request', async () => {
    mock.onGet('/users?page=1&pageSize=10').reply(200, { success: true, users: [{ ...target, id: actor.id, username: actor.username, roleId: roles[0].id, role: 'ADMIN' }], total: 1, pageSize: 10 })
    await show('/admin/users', 'User Role Assignment')
    await userEvent.setup().click(await screen.findByRole('button', { name: `Edit role for ${actor.username}` }))
    await userEvent.setup().selectOptions(screen.getByRole('combobox'), roles[1].id)
    await userEvent.setup().click(screen.getByRole('button', { name: 'Save role' }))
    const alert = screen.getByRole('alertdialog', { name: 'Change your own role?' })
    expect(mock.history.put).toHaveLength(0)
    await userEvent.setup().click(within(alert).getByRole('button', { name: 'Cancel' }))
    expect(screen.getByRole('dialog', { name: 'Edit User Role' })).toBeInTheDocument()
    expect(mock.history.put).toHaveLength(0)
  })
  it('creates a menu using API field names and prevents duplicate submits', async () => {
    await show('/admin/menus', 'Menu Management')
    await screen.findByRole('table', { name: 'All menus' })
    await userEvent.setup().click(screen.getByRole('button', { name: 'Add menu', exact: true }))
    fireEvent.change(screen.getByLabelText('Menu name'), { target: { value: 'New menu' } })
    let finish
    mock.onPost('/menus').reply(() => new Promise((resolve) => { finish = resolve }))
    await userEvent.setup().dblClick(screen.getByRole('button', { name: 'Save menu' }))
    expect(mock.history.post.filter((r) => r.url === '/menus')).toHaveLength(1)
    expect(JSON.parse(mock.history.post.at(-1).data)).toEqual({ menuName: 'New menu', menuPath: null, menuIcon: null, parentId: null, sortOrder: 0, isActive: true })
    await act(async () => finish([201, { success: true, menu: { id: uuid(99) } }]))
    await screen.findByText('Menu saved.')
  })
  it('edits menu details and surfaces backend 409 without losing the form', async () => {
    await show('/admin/menus', 'Menu Management')
    await userEvent.setup().click(await screen.findByRole('button', { name: 'Edit Profile' }))
    mock.onPut(`/menus/${uuid(2)}`).reply(409, { success: false, message: 'Critical or dependency conflict' })
    await userEvent.setup().click(screen.getByRole('button', { name: 'Save menu' }))
    await screen.findByRole('alert', { name: '' })
    expect(screen.getByLabelText('Menu name')).toHaveValue('Profile')
    expect(mock.history.put[0].url).toBe(`/menus/${uuid(2)}`)
  })
  it('cancelled deletion never sends a DELETE request', async () => {
    await show('/admin/menus', 'Menu Management')
    await userEvent.setup().click(await screen.findByRole('button', { name: 'Delete Profile' }))
    await userEvent.setup().click(within(screen.getByRole('alertdialog')).getByRole('button', { name: 'Cancel' }))
    expect(mock.history.delete).toHaveLength(0)
  })
  it('creates roles, edits only name and displays delete dependency errors', async () => {
    await show('/admin/roles', 'Role Management')
    await userEvent.setup().click(screen.getByRole('button', { name: 'Add role', exact: true }))
    fireEvent.change(screen.getByLabelText('Role code'), { target: { value: 'auditor' } })
    fireEvent.change(screen.getByLabelText('Role name'), { target: { value: 'Auditor' } })
    mock.onPost('/roles').reply(201, { success: true, role: { id: uuid(80) } })
    await userEvent.setup().click(screen.getByRole('button', { name: 'Save role' }))
    await waitFor(() => expect(mock.history.post).toHaveLength(1))
    expect(JSON.parse(mock.history.post[0].data)).toEqual({ code: 'AUDITOR', name: 'Auditor' })
    await waitFor(() => expect(screen.queryByLabelText('Role code')).not.toBeInTheDocument())
    await userEvent.setup().click(screen.getByRole('button', { name: 'Edit USER' }))
    expect(screen.getByLabelText('Role code')).toBeDisabled()
    mock.onPut(`/roles/${roles[2].id}`).reply(200, { success: true, role: roles[2] })
    await userEvent.setup().click(screen.getByRole('button', { name: 'Save role' }))
    await waitFor(() => expect(mock.history.put).toHaveLength(1))
    expect(JSON.parse(mock.history.put[0].data)).toEqual({ name: 'USER' })
    mock.onDelete(`/roles/${roles[2].id}`).reply(409, { success: false, message: 'Role still has users' })
    await userEvent.setup().click(screen.getByRole('button', { name: 'Delete USER' }))
    await userEvent.setup().click(within(screen.getByRole('alertdialog')).getByRole('button', { name: 'Delete role' }))
    await screen.findByText('Role still has users', { selector: 'p' })
  })
  it('assigns explicit checkbox IDs and allows clearing all grants', async () => {
    await show('/admin/roles', 'Role Management')
    await userEvent.setup().click(await screen.findByRole('button', { name: 'Assign menus to USER' }))
    const form = await screen.findByRole('form', { name: 'Assign menus' })
    await userEvent.setup().click(within(form).getByRole('checkbox', { name: 'Profile /profile' }))
    mock.onPut(`/roles/${roles[2].id}/menus`).reply(200, { success: true, role: roles[2], menuIds: [] })
    await userEvent.setup().click(within(form).getByRole('button', { name: 'Save permissions' }))
    await waitFor(() => expect(mock.history.put).toHaveLength(1))
    expect(JSON.parse(mock.history.put[0].data)).toEqual({ menuIds: [] })
  })
  it('changes only the selected target user and keeps the administrator identity', async () => {
    await show('/admin/users', 'User Role Assignment')
    await userEvent.setup().click(await screen.findByRole('button', { name: 'Edit role for target_fixture' }))
    const form = await screen.findByRole('form', { name: 'Change role for target_fixture' })
    await userEvent.setup().selectOptions(within(form).getByRole('combobox'), roles[1].id)
    mock.onPut(`/users/${target.id}/role`).reply(200, { success: true, user: { ...target, role: 'MANAGER' } })
    await userEvent.setup().click(within(form).getByRole('button', { name: 'Save role' }))
    await waitFor(() => expect(mock.history.put).toHaveLength(1))
    expect(JSON.parse(mock.history.put[0].data)).toEqual({ roleId: roles[1].id })
    expect(screen.getByTestId('account')).toHaveTextContent(actor.username)
  })
  it('supports user pagination and resource retry', async () => {
    mock.onGet('/users?page=1&pageSize=10').reply(200, { success: true, users: [target], total: 11, pageSize: 10 })
    mock.onGet('/users?page=2&pageSize=10').networkErrorOnce()
    mock.onGet('/users?page=2&pageSize=10').reply(200, { success: true, users: [], total: 11, pageSize: 10 })
    await show('/admin/users', 'User Role Assignment')
    await userEvent.setup().click(await screen.findByRole('button', { name: 'Next' }))
    await userEvent.setup().click(await screen.findByRole('button', { name: 'Retry' }))
    await screen.findByText('No users found.')
    expect(screen.getByText('Page 2 · 11 users')).toBeInTheDocument()
  })
})
